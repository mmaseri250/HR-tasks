function parseCSV(text) {
  const lines = text.trim().split('\n');
  const headers = lines[0].split(',');
  const rows = [];
  for (let i = 1; i < lines.length; i++) {
    const parts = lines[i].split(',');
    if (parts.length >= 18) {
      const obj = {};
      headers.forEach((h, idx) => {
        obj[h.trim()] = (parts[idx] || '').trim();
      });
      rows.push(obj);
    }
  }
  return rows;
}

