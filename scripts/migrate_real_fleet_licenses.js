function migrate() {
  const { run, query } = require('../server/database/db');
  console.log('=== Starting Real Fleet & Licenses Migration ===');

  // 1. Migrate Vehicles (23 vehicles)
  run('DELETE FROM vehicles');
  console.log('Cleared old vehicles table');

  const insertVehicle = `
    INSERT INTO vehicles (
      plate_number_ar, plate_number_en, make, model, year, color,
      vin_serial, vehicle_type, odometer, status, tamm_status,
      assigned_emp_id, assigned_emp_name, assigned_date, istimara_expiry, fahas_expiry,
      insurance_company, insurance_policy_no, insurance_expiry
    ) VALUES (
      ?, ?, ?, ?, ?, ?,
      ?, ?, ?, ?, ?,
      ?, ?, ?, ?, ?,
      ?, ?, ?
    )
  `;

  for (const v of realVehicles) {
    run(insertVehicle, [
      v.plate_number_ar,
      v.plate_number_en,
      v.make,
      v.model,
      v.year,
      v.color,
      v.vin_serial,
      v.vehicle_type,
      v.odometer,
      v.status,
      v.tamm_status,
      v.assigned_emp_id || null,
      v.assigned_emp_name,
      v.assigned_date,
      v.istimara_expiry,
      v.fahas_expiry,
      v.insurance_company,
      v.insurance_policy_no,
      v.insurance_expiry
    ]);
  }
  const vCount = query('SELECT COUNT(*) as count FROM vehicles')[0].count;
  console.log(`Successfully migrated ${vCount} vehicles into vehicles table.`);

  // 2. Migrate Licenses (17 official government licenses)
  run('DELETE FROM company_licenses');
  console.log('Cleared old company_licenses table');

  const insertLicense = `
    INSERT INTO company_licenses (
      license_type, license_name_ar, license_no, issuing_authority,
      issue_date, expiry_date, alert_days_before, status, notes
    ) VALUES (
      ?, ?, ?, ?,
      ?, ?, ?, ?, ?
    )
  `;

  for (const lic of realLicenses) {
    run(insertLicense, [
      lic.license_type,
      lic.facility_name,
      lic.license_number,
      lic.issuer,
      lic.issue_date,
      lic.expiry_date_gregorian || lic.expiry_date,
      lic.alert_days_before || 30,
      lic.status || 'ساري',
      lic.notes || ''
    ]);
  }
  const lCount = query('SELECT COUNT(*) as count FROM company_licenses')[0].count;
  console.log(`Successfully migrated ${lCount} licenses into company_licenses table.`);
  console.log('=== Migration Complete: All 23 Vehicles and 17 Licenses Ready ===');
}

